#!/bin/sh
# Regenerates THIRD_PARTY_LICENSES from the real licence files of every Go module that
# is compiled into lazycode on Linux, macOS or Windows (go list -deps), plus Go itself.
# It needs the modules in the module cache: run `go mod download` first if it's empty.
#
# A module with no licence file, or whose licence it doesn't recognise as one of the
# permissive ones below, is FLAGGED: in the output file, on stderr, and in the exit
# status (1). The script doesn't guess: a person has to read the file and decide.
#
# Usage: scripts/third-party-licenses.sh
set -eu

cd "$(dirname "$0")/.."
out=THIRD_PARTY_LICENSES
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# "path version dir" for each non-main module, over the three operating systems.
for goos in linux darwin windows; do
	GOOS=$goos GOARCH=amd64 CGO_ENABLED=1 go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/lazycode
done | sort -u >"$tmp/modules"

# What kind of licence is this file? Prints a name, or nothing if it isn't recognised.
kind() {
	if grep -q 'Unicode, Inc\.' "$1" && grep -q 'Unicode data files' "$1"; then echo Unicode
	elif grep -q 'Apache License' "$1" && grep -q 'Version 2.0' "$1"; then echo Apache-2.0
	elif grep -qi 'Permission is hereby granted, free of charge' "$1"; then echo MIT
	elif grep -q 'Permission to use, copy, modify, and/or distribute this software' "$1"; then echo ISC
	elif grep -q 'Neither the name of' "$1" && grep -q 'Redistribution and use in source and binary forms' "$1"; then echo BSD-3-Clause
	elif grep -q 'Redistribution and use in source and binary forms' "$1"; then echo BSD-2-Clause
	fi
}

flags="$tmp/flags"
: >"$flags"
{
	cat <<'HEAD'
THIRD PARTY LICENSES

LazyCode is MIT licensed (see LICENSE). It includes the software below, each under its
own licence, reproduced here from the files in the modules themselves. Apache-2.0
software (tcell) keeps its licence text and any NOTICE with it.

This file is generated by scripts/third-party-licenses.sh. Don't edit it by hand.

HEAD
	printf 'Go standard library (%s)\n' "$(go env GOVERSION)"
	echo '--------------------------------------------------------------------------------'
	cat "$(go env GOROOT)/LICENSE"
	echo
	while read -r path version dir; do
		found=0
		# Licence files at the top of the module, and in folders such as src/ that hold
		# bundled code. Folders named bindings are separate modules, and cmd folders are tools that are not built in.
		find "$dir" -maxdepth 3 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \) -not -path '*/bindings/*' -not -path '*/cmd/*' | sort >"$tmp/files"
		while read -r f; do
			found=1
			rel=${f#"$dir"/}
			k=$(kind "$f")
			case $(basename "$f") in
			NOTICE* | PATENTS*) k=notice ;;
			esac
			[ -n "$k" ] || echo "$path $version: $rel isn't a licence this script recognises. Read it." >>"$flags"
			printf '%s %s\n%s (detected: %s)\n' "$path" "$version" "$rel" "${k:-UNRECOGNISED}"
			echo '--------------------------------------------------------------------------------'
			cat "$f"
			echo
		done <"$tmp/files"
		if [ "$found" = 0 ]; then
			echo "$path $version: no licence file found." >>"$flags"
			printf '%s %s\nNO LICENCE FILE FOUND: see the flags at the end of this file.\n\n' "$path" "$version"
		fi
	done <"$tmp/modules"
	if [ -s "$flags" ]; then
		echo 'FLAGS: these need a person to read the licence, and are not decided:'
		cat "$flags"
	fi
} >"$tmp/out"

mv "$tmp/out" "$out"
echo "Wrote $out: $(wc -l <"$tmp/modules") modules, $(wc -l <"$out") lines."
if [ -s "$flags" ]; then
	echo "FLAGS:" >&2
	cat "$flags" >&2
	exit 1
fi
